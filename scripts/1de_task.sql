SET PAGESIZE 1000

DESC system.tabell;

-- Antal beviljade ansökningar 
SELECT
    UTBILDNINGSOMRÅDE,
    UTBILDNINGSNAMN,
    COUNT(CASE WHEN BESLUT = 'Beviljad' THEN 1 END) AS ANTAL_BEVILJADE_ANSÖKNINGAR
FROM
    tabell
WHERE
    BESLUT = 'Beviljad'
    AND UTBILDNINGSOMRÅDE = 'Data/IT'
GROUP BY
    UTBILDNINGSOMRÅDE,
    UTBILDNINGSNAMN
ORDER BY
    ANTAL_BEVILJADE_ANSÖKNINGAR DESC;

-- Antal avslagna ansökningar
SELECT
    UTBILDNINGSOMRÅDE,
    UTBILDNINGSNAMN,
    COUNT(CASE WHEN BESLUT = 'Avslag' THEN 1 END) AS ANTAL_AVSLAGNA_ANSÖKNINGAR
FROM
    tabell
WHERE
    BESLUT = 'Avslag'
    AND UTBILDNINGSOMRÅDE = 'Data/IT'
GROUP BY
    UTBILDNINGSOMRÅDE,
    UTBILDNINGSNAMN
ORDER BY 
    ANTAL_AVSLAGNA_ANSÖKNINGAR DESC;
